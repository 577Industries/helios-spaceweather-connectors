def _seed_cache(cache_root: Path, year: int, doy: int, center: str) -> None:
    """Plant the synthetic IONEX in the adapter's raw cache so the
    download path is bypassed entirely (cache hit on first lookup)."""

    day_dir = cache_root / f"{year:04d}" / f"{doy:03d}"
    day_dir.mkdir(parents=True, exist_ok=True)
    target = day_dir / f"{center}_{year:04d}_{doy:03d}.ionex"
    target.write_bytes(SYNTHETIC_PLAIN.read_bytes())


@pytest.mark.asyncio
async def test_fetch_tec_maps_yields_per_2h_records(
    _stub_earthdata_env: None, tmp_path: Path
) -> None:
    _seed_cache(tmp_path, 2024, 131, "igsg")
    adapter = CddisGimAdapter(cache=False, cache_root=tmp_path, use_earthaccess=False)
    try:
        records: list[Any] = []
        async for rec in adapter.fetch_tec_maps(start=GANNON_DAY_START, end=GANNON_DAY_END):
            records.append(rec)
        assert len(records) == 13  # 00, 02, 04, ..., 24 UTC
        # Every record carries the expected provenance shape.
        assert all(rec.source == SourceID.CDDIS_GIM for rec in records)
        assert all(rec.record_type == "tec_map" for rec in records)
        assert all(rec.value_units == "TECU" for rec in records)
        # Grid dimensions
        first_grid = records[0].value["tec_grid"]
        assert len(first_grid) == 71
        assert len(first_grid[0]) == 73
        # Lineage cites the analysis-center name
        assert records[0].provenance.extra is not None
        assert "IGS combined" in records[0].provenance.extra["lineage"]
    finally:
        await adapter.aclose()


@pytest.mark.asyncio
async def test_fetch_tec_at_point_gannon_storm_elevated(
    _stub_earthdata_env: None, tmp_path: Path
) -> None:
    """The headline regression test: TEC at Columbus, OH spikes above
    30 TECU during the Gannon storm peak."""

    _seed_cache(tmp_path, 2024, 131, "igsg")
    adapter = CddisGimAdapter(cache=False, cache_root=tmp_path, use_earthaccess=False)
    try:
        records: list[Any] = []
        async for rec in adapter.fetch_tec_at_point(
            start=GANNON_DAY_START,
            end=GANNON_DAY_END,
            lat=40.0,
            lon=-83.0,
        ):
            records.append(rec)
        # All 13 epochs covered.
        assert len(records) == 13
        # Peak TEC during the storm-amplified window (around 20 UT) must
        # exceed 30 TECU — matches the published Gannon-storm enhancement
        # (>50 TECU) over the U.S. Midwest, and the synthetic fixture's
        # built-in Gaussian bump that mimics it.
        peak_tec = max(rec.value["tec"] for rec in records)
        assert peak_tec > 30.0, f"expected peak > 30 TECU; got {peak_tec:.1f}"
        # Peak should be at or near 20 UT.
        peak_record = max(records, key=lambda r: r.value["tec"])
        assert 18 <= peak_record.event_time.hour <= 22
    finally:
        await adapter.aclose()


