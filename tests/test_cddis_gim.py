def test_decompress_z_rejects_bad_magic() -> None:
    with pytest.raises(ValueError, match=r"not a \.Z"):
        _decompress_unix_z(b"not-a-Z-file")


def test_decompress_z_without_unlzw3_raises_runtime_error(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """If a user requests a pre-2023 .Z file without the [earthdata] extra
    installed, we raise a clear actionable RuntimeError pointing them at
    the right pip install."""

    # Force ``import unlzw3`` to fail inside _decompress_unix_z.
    import builtins

    real_import = builtins.__import__

    def fake_import(name: str, *a: Any, **kw: Any) -> Any:
        if name == "unlzw3":
            raise ImportError("forced for test")
        return real_import(name, *a, **kw)

    monkeypatch.setattr(builtins, "__import__", fake_import)
    # Magic header is correct so we fall through to the import.
    fake_z = b"\x1f\x9d\x90"
    with pytest.raises(RuntimeError, match="unlzw3"):
        _decompress_unix_z(fake_z)


def test_decompress_dispatch_on_extension() -> None:
    """``_decompress_ionex`` routes by suffix: .gz, .Z, or passthrough."""

    payload = b"plain text"
    # .GZ (uppercase) should also be detected (defensive).
    gz = gzip.compress(payload)
    assert _decompress_ionex(gz, "FOO.INX.GZ") == payload


