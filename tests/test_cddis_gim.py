@pytest.mark.asyncio
async def test_cache_round_trip(_stub_earthdata_env: None, tmp_path: Path) -> None:
    """The first request populates the cache; the second is a pure
    cache hit and does not touch the (404-only) mock transport."""

    transport = _mock_transport_404_then_synthetic()
    client = httpx.AsyncClient(transport=transport, base_url=CDDIS_BASE_URL)
    adapter = CddisGimAdapter(
        client=client, cache=False, cache_root=tmp_path, use_earthaccess=False
    )
    try:
        # First pass: populates cache.
        recs1 = [
            r async for r in adapter.fetch_tec_maps(start=GANNON_DAY_START, end=GANNON_DAY_END)
        ]
        first_call_count = len(transport._calls)  # type: ignore[attr-defined]
        # Second pass: same window, should be a pure cache hit.
        recs2 = [
            r async for r in adapter.fetch_tec_maps(start=GANNON_DAY_START, end=GANNON_DAY_END)
        ]
        second_call_count = len(transport._calls)  # type: ignore[attr-defined]
        assert len(recs1) == len(recs2) == 13
        assert second_call_count == first_call_count, "expected no new HTTP calls"
    finally:
        await adapter.aclose()


