"""Tests for the CDDIS GIM adapter.

The unit tests exercise:

* The IONEX parser against a synthetic fixture committed under
  ``tests/fixtures/cddis_gim/``. The fixture is regenerated by
  ``tests/fixtures/cddis_gim/_generate_synthetic.py`` so reviewers can
  audit the assumed analytic TEC distribution.
* The Earthdata authentication flow (env-var detection, missing-credentials
  error, ``earthaccess`` opt-in, manual httpx fallback).
* The download routing (legacy ``.Z`` vs long-form ``.gz`` filename
  conventions), with mocked httpx responses.
* The unified streaming :meth:`fetch_tec_maps` and the bilinear-point
  :meth:`fetch_tec_at_point` paths, end-to-end against the synthetic
  fixture as if it were the live CDDIS response.

The *critical* assertion is the Gannon-storm smoke test: a
``fetch_tec_at_point(lat=40.0, lon=-83.0)`` call across the May 10-11
2024 window yields TEC > 30 TECU at the storm-peak epoch. With the
synthetic fixture this asserts the parser + bilinear-interp + diurnal
modelling are all wired correctly; the same test is also marked
``@pytest.mark.live`` with the real CDDIS URL for nightly runs.
"""

