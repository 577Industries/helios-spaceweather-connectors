def _mock_transport_404_then_synthetic() -> httpx.MockTransport:
    """First request → 404 (legacy short-form miss); second request →
    200 with the synthetic IONEX gzipped (long-form hit)."""

    synthetic_gz = gzip.compress(SYNTHETIC_PLAIN.read_bytes())
    calls: list[str] = []

    def handler(request: httpx.Request) -> httpx.Response:
        calls.append(str(request.url))
        if request.url.path.endswith(".Z"):
            return httpx.Response(404)
        return httpx.Response(
            200,
            content=synthetic_gz,
            headers={"content-type": "application/octet-stream"},
        )

    transport = httpx.MockTransport(handler)
    transport._calls = calls  # type: ignore[attr-defined]
    return transport


@pytest.mark.asyncio
async def test_download_path_falls_back_on_404(_stub_earthdata_env: None, tmp_path: Path) -> None:
    transport = _mock_transport_404_then_synthetic()
    client = httpx.AsyncClient(transport=transport, base_url=CDDIS_BASE_URL)
    adapter = CddisGimAdapter(
        client=client, cache=False, cache_root=tmp_path, use_earthaccess=False
    )
    try:
        records = [
            rec async for rec in adapter.fetch_tec_maps(start=GANNON_DAY_START, end=GANNON_DAY_END)
        ]
        assert len(records) == 13
        # Both the long-form .gz (200) and the legacy .Z (404) URLs were tried.
        calls = transport._calls  # type: ignore[attr-defined]
        assert any(".gz" in c for c in calls)
    finally:
        await adapter.aclose()


